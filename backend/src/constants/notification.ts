// src/constants/notification.ts

export const NOTIFICATION_CATEGORY = {
  WORKOUT: "WORKOUT",
  NUTRITION: "NUTRITION",
  COACHING: "COACHING",
  ACHIEVEMENT: "ACHIEVEMENT",
  SYSTEM: "SYSTEM",
} as const;

export type NotificationCategory =
  (typeof NOTIFICATION_CATEGORY)[keyof typeof NOTIFICATION_CATEGORY];

export const NOTIFICATION_TYPE = {
  // Workout
  ASSIGNMENT_CREATED: "ASSIGNMENT_CREATED",
  ASSIGNMENT_UPDATED: "ASSIGNMENT_UPDATED",
  ASSIGNMENT_CANCELLED: "ASSIGNMENT_CANCELLED",
  WORKOUT_COMPLETED: "WORKOUT_COMPLETED",
  WORKOUT_STARTED: "WORKOUT_STARTED",
  WORKOUT_SCHEDULED: "WORKOUT_SCHEDULED",
  WORKOUT_SCHEDULE_UPDATED: "WORKOUT_SCHEDULE_UPDATED",
  WORKOUT_SCHEDULE_CANCELLED: "WORKOUT_SCHEDULE_CANCELLED",

  // Nutrition
  NUTRITION_PLAN_ASSIGNED: "NUTRITION_PLAN_ASSIGNED",
  NUTRITION_PLAN_UPDATED: "NUTRITION_PLAN_UPDATED",

  // Body Measurement & Progress
  BODY_MEASUREMENT_CREATED: "BODY_MEASUREMENT_CREATED",
  BODY_MEASUREMENT_UPDATED: "BODY_MEASUREMENT_UPDATED",
  BODY_MEASUREMENT_DELETED: "BODY_MEASUREMENT_DELETED",

  // Coaching & Relationships
  COACHING_INVITATION_RECEIVED: "COACHING_INVITATION_RECEIVED",
  COACHING_INVITATION_ACCEPTED: "COACHING_INVITATION_ACCEPTED",
  COACHING_INVITATION_DECLINED: "COACHING_INVITATION_DECLINED",
  COACHING_RELATIONSHIP_TERMINATED: "COACHING_RELATIONSHIP_TERMINATED",
  HISTORY_SHARING_GRANTED: "HISTORY_SHARING_GRANTED",
  HISTORY_SHARING_REVOKED: "HISTORY_SHARING_REVOKED",

  // Appointments
  COACHING_APPOINTMENT_SCHEDULED: "COACHING_APPOINTMENT_SCHEDULED",
  COACHING_APPOINTMENT_RESCHEDULED: "COACHING_APPOINTMENT_RESCHEDULED",
  COACHING_APPOINTMENT_CANCELLED: "COACHING_APPOINTMENT_CANCELLED",
  COACHING_APPOINTMENT_COMPLETED: "COACHING_APPOINTMENT_COMPLETED",
  COACHING_APPOINTMENT_NO_SHOW: "COACHING_APPOINTMENT_NO_SHOW",

  // Gamification & Achievements
  ACHIEVEMENT_UNLOCKED: "ACHIEVEMENT_UNLOCKED",
  STREAK_MILESTONE: "STREAK_MILESTONE",
  WEEKLY_GOAL_COMPLETED: "WEEKLY_GOAL_COMPLETED",
  COACH_ENCOURAGEMENT: "COACH_ENCOURAGEMENT",

  // System
  SYSTEM: "SYSTEM",
} as const;

export type NotificationType =
  (typeof NOTIFICATION_TYPE)[keyof typeof NOTIFICATION_TYPE];

export const getCategoryForNotificationType = (
  type: string,
): NotificationCategory => {
  switch (type) {
    case NOTIFICATION_TYPE.ASSIGNMENT_CREATED:
    case NOTIFICATION_TYPE.ASSIGNMENT_UPDATED:
    case NOTIFICATION_TYPE.ASSIGNMENT_CANCELLED:
    case NOTIFICATION_TYPE.WORKOUT_COMPLETED:
    case NOTIFICATION_TYPE.WORKOUT_STARTED:
    case NOTIFICATION_TYPE.WORKOUT_SCHEDULED:
    case NOTIFICATION_TYPE.WORKOUT_SCHEDULE_UPDATED:
    case NOTIFICATION_TYPE.WORKOUT_SCHEDULE_CANCELLED:
      return NOTIFICATION_CATEGORY.WORKOUT;

    case NOTIFICATION_TYPE.NUTRITION_PLAN_ASSIGNED:
    case NOTIFICATION_TYPE.NUTRITION_PLAN_UPDATED:
      return NOTIFICATION_CATEGORY.NUTRITION;

    case NOTIFICATION_TYPE.BODY_MEASUREMENT_CREATED:
    case NOTIFICATION_TYPE.BODY_MEASUREMENT_UPDATED:
    case NOTIFICATION_TYPE.BODY_MEASUREMENT_DELETED:
    case NOTIFICATION_TYPE.COACHING_INVITATION_RECEIVED:
    case NOTIFICATION_TYPE.COACHING_INVITATION_ACCEPTED:
    case NOTIFICATION_TYPE.COACHING_INVITATION_DECLINED:
    case NOTIFICATION_TYPE.COACHING_RELATIONSHIP_TERMINATED:
    case NOTIFICATION_TYPE.HISTORY_SHARING_GRANTED:
    case NOTIFICATION_TYPE.HISTORY_SHARING_REVOKED:
    case NOTIFICATION_TYPE.COACHING_APPOINTMENT_SCHEDULED:
    case NOTIFICATION_TYPE.COACHING_APPOINTMENT_RESCHEDULED:
    case NOTIFICATION_TYPE.COACHING_APPOINTMENT_CANCELLED:
    case NOTIFICATION_TYPE.COACHING_APPOINTMENT_COMPLETED:
    case NOTIFICATION_TYPE.COACHING_APPOINTMENT_NO_SHOW:
    case NOTIFICATION_TYPE.COACH_ENCOURAGEMENT:
      return NOTIFICATION_CATEGORY.COACHING;

    case NOTIFICATION_TYPE.ACHIEVEMENT_UNLOCKED:
    case NOTIFICATION_TYPE.STREAK_MILESTONE:
    case NOTIFICATION_TYPE.WEEKLY_GOAL_COMPLETED:
      return NOTIFICATION_CATEGORY.ACHIEVEMENT;

    case NOTIFICATION_TYPE.SYSTEM:
    default:
      return NOTIFICATION_CATEGORY.SYSTEM;
  }
};
